import { build } from 'esbuild'
import assert from 'node:assert/strict'
const bundle = await build({ stdin: { contents: "export * from './src/game3/action/stories'; export { Village } from './src/game3/action/village'; export { blocked } from './src/game3/action/layout'", resolveDir: process.cwd() }, bundle: true, write: false, format: 'esm', platform: 'node' })
const { VillageStories, CONTACTS, Village, blocked } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`)
const order = (kind, cargo) => ({ kind, cargo, title: '先前的政令', target: { x: 450, y: 330 }, required: 3, brief: '' })
const book = new VillageStories()
assert.equal(book.offer('qiao', 0), undefined)
book.record(order('relief'), false, 0)
assert.equal(book.offer('qiao', 1), undefined, 'unsuccessful relief does not invent a rescued household')
book.record(order('relief'), true, 1)
assert.equal(book.offer('qiao', 1), undefined, 'follow-ups wait until the next main decision')
assert.equal(book.offer('qiao', 2).choices.length, 2)
assert.equal(book.begin('qiao', 'invalid', 2), undefined)
assert.equal(book.begin('qiao', 'school', 2).order.cargo, '义学物资')
assert.equal(book.begin('qiao', 'wall', 2), undefined, 'only one branch can be selected')
book.acknowledge();assert.equal(book.active, 'qiao', 'an unfinished mission cannot be acknowledged')
book.finish(true);assert.ok(book.memory('qiao').includes('义学'))
book.finish(false);assert.equal(book.current.success, true, 'completion cannot be overwritten')
book.acknowledge();book.record(order('relief'), true, 8)
assert.equal(book.offer('qiao', 9), undefined, 'completed stories cannot be farmed')
assert.equal(book.all().length, 1)
for (const success of [true, false]) {
  const routes = new VillageStories();routes.record(order('escort'), success, 3)
  const offer = routes.offer('an', 4)
  assert.equal(offer.choices[0].order.kind, success ? 'escort' : 'assault', 'the caravan outcome changes the next playable task')
  assert.equal(offer.choices[1].order.convoy, 'people')
  assert.equal(offer.cause.includes('受挫'), !success)
  routes.begin('an', 'people', 4);routes.finish(false)
  assert.ok(routes.memory('an').includes('没办成'), 'failed follow-ups never claim success')
}
const care = new VillageStories();care.record(order('assault'), true, 0)
assert.equal(care.offer('wan', 1), undefined)
care.record(order('assault'), false, 1)
assert.ok(care.offer('wan', 2).body.includes('伤者'))
const medicine = new VillageStories();medicine.record(order('relief', '药材'), true, 0)
assert.ok(medicine.offer('wan', 1).body.includes('病人'))
const village = new Village(), people = village.people.filter(p => p.contactId)
assert.equal(people.length, 3)
for (const p of people) assert.equal(blocked(p, 17), false, `${p.name} stands in a reachable place`)
village.setRealm({ military: 0, politics: 0, economy: 0, destiny: 0 })
village.setRealm({ military: 100, politics: 100, economy: 100, destiny: 100 })
assert.deepEqual(village.people.filter(p => p.contactId).map(p => p.id), people.map(p => p.id), 'recurring people survive crowd changes')
assert.deepEqual(new Set(people.map(p => p.contactId)), new Set(CONTACTS.map(c => c.id)))
console.log('PASS: outcome-dependent requests, delayed availability, exclusive branches, success/failure memories, replay guards, persistent reachable characters')
