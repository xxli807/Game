// ---------- 鼎革：手写事件库 ----------
// 替换原先 Array.from({ length: 83 }) 生成的模板事件（「乱世传闻 · 37」那批）：
// 标题带编号、正文只换城市名、选项永远是「招揽 X / 整顿 Y」，一局抽 20 个很快就被看穿。
// 文本游戏的命脉是文本，这里把它补上。
//
// 单独成文件：tim.lu 的 authoredEvents 与 CHALLENGES 仍原样留在 App.tsx。
//
// 写作约定
// 1. 每个事件是一个**具体场景**，不是一句设定说明——先给画面，再给两难。
// 2. 两个选项都要有代价。没有「明显更好」的那一个，否则抉择就退化成领奖。
// 3. 两个选项压在**不同的资源轴**上（粮↔兵、民心↔稳定、威望↔实利），
//    逼玩家在 21 次抉择里长出一条路线，而不是每次都拿最大的数字。
// 4. 人才只用 rules.ts 的 TALENT_BOONS 已定义的 11 位，
//    否则新名字会变成没有加成的收集物——那正是原来的毛病。
// 5. detail 文本必须与 effect 数值一致：玩家是照着它做决定的。

export type Phase = '蛰伏' | '立足' | '逐鹿' | '问鼎' | '建国'
export type Effect = { grain?: number; silver?: number; morale?: number; prestige?: number; army?: number; city?: string; talent?: string; spouse?: string; armyType?: string; stability?: number; death?: boolean }
export type EventOption = { label: string; detail: string; effect: Effect; success?: number; reward?: Effect }
export type GameEvent = { id: string; title: string; body: string; source: string; options: EventOption[]; phase: Phase }

type Opt = [label: string, detail: string, effect: Effect]
const ev = (id: string, phase: Phase, source: string, title: string, body: string, a: Opt, b: Opt): GameEvent => ({
  id, phase, source, title, body,
  options: [{ label: a[0], detail: a[1], effect: a[2] }, { label: b[0], detail: b[1], effect: b[2] }],
})

